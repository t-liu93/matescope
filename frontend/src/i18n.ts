function updateDocumentLanguage(language: string) {
  document.documentElement.lang = language.startsWith("zh") ? "zh" : "en";
}

export function suggestedLanguage(languages: readonly string[]): "en" | "zh" {
  for (const language of languages) {
    const baseLanguage = language.toLowerCase().split("-", 1)[0];
    if (baseLanguage === "en" || baseLanguage === "zh") return baseLanguage;
  }
  return "en";
}

const initialLanguage = suggestedLanguage(
  navigator.languages.length > 0 ? navigator.languages : [navigator.language],
);
updateDocumentLanguage(initialLanguage);
i18n.on("languageChanged", updateDocumentLanguage);
void i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});
export default i18n;
